import { getServerConfig } from "./serverConfig";
import { listCharacters } from "./characters";
import { WorkoutSession, WorkoutSet } from "../src/workout/types";

/**
 * Read-only client for a self-hosted wger instance (https://wger.de) —
 * real workout data, replacing/underlaying the mock mirror in
 * server/workouts.ts (see that file's own comment for the dispatch logic).
 *
 * Auth: a wger DRF API token, sent as `Authorization: Token <value>` (NOT
 * `Bearer` — that's a different header convention this API doesn't use).
 * There is no "quickstart default" token — it has to be generated by hand
 * from the wger web UI: log in, go to Preferences > API key, click
 * "Generate new API key", and paste the resulting value into
 * server_config.wger_api_token (see server/serverConfig.ts). wger's own
 * default *account* on a fresh docker-compose install is admin/adminadmin,
 * confirmed against a live instance while building this — but the API
 * token itself is still a manual step with no API shortcut to skip it
 * (wger's session-login endpoint uses django-allauth's "login" field name,
 * not "username", and has no token-issuing endpoint of its own — the only
 * way to get one is that UI page).
 *
 * Scope: one DRF token = one wger account = one person's workout history
 * (wger has no concept of "read-only scoped" tokens — a token can read/
 * write everything its account owns, so this client enforces read-only
 * behavior itself by only ever issuing GET requests). That means this
 * integration is inherently single-account, not per-House-Simulator-
 * character the way AW tracking is — see resolveWgerCharacterId() below
 * for how that one account's data gets attributed to one character.
 */

interface WgerConfig {
  baseUrl: string;
  apiToken: string;
}

function configOrNull(): WgerConfig | null {
  const { wgerBaseUrl, wgerApiToken } = getServerConfig();
  if (!wgerBaseUrl || !wgerApiToken) return null;
  return { baseUrl: wgerBaseUrl.replace(/\/+$/, ""), apiToken: wgerApiToken };
}

export function isWgerConfigured(): boolean {
  return configOrNull() !== null;
}

/**
 * Which House Simulator character the one configured wger account belongs
 * to. `server_config.wger_character_id` is the explicit, admin-set
 * override (same "hand-edited on the server" convention as
 * broadcast_url/lan_secret/admin_secret); absent that, this falls back to
 * whichever character is named "Jacqueline" — the same one-account
 * assumption server/index.ts's old mock-seeding call already made
 * ("only for Jacqueline specifically"), so a fresh install with real wger
 * credentials set just works without an extra manual step, while still
 * leaving room for an explicit override if that assumption ever stops
 * holding (e.g. Kevin gets his own wger account/token later).
 */
export function resolveWgerCharacterId(): string | null {
  const { wgerCharacterId } = getServerConfig();
  if (wgerCharacterId) return wgerCharacterId;
  return listCharacters().find((c) => c.name === "Jacqueline")?.id ?? null;
}

export function isWgerLinkedCharacter(characterId: string): boolean {
  return isWgerConfigured() && resolveWgerCharacterId() === characterId;
}

const FETCH_TIMEOUT_MS = 5000;
// Bounded pagination for safe reads (per the implementation brief's Phase 1
// — see wger_gamification_implementation_plan.md) — today's own logged
// data is never remotely this large, this just guards against a
// misconfigured date filter turning into an unbounded crawl of the whole
// account's history.
const MAX_PAGES = 10;

interface WgerPage<T> {
  next: string | null;
  results: T[];
}

async function wgerFetch(path: string): Promise<Response> {
  const config = configOrNull();
  if (!config) throw new Error("wger is not configured (server_config.wger_base_url/wger_api_token)");

  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), FETCH_TIMEOUT_MS);
  try {
    const res = await fetch(`${config.baseUrl}${path}`, {
      headers: { Authorization: `Token ${config.apiToken}` },
      signal: controller.signal,
    });
    return res;
  } finally {
    clearTimeout(timeout);
  }
}

async function wgerGetJson<T>(path: string): Promise<T> {
  const res = await wgerFetch(path);
  if (!res.ok) {
    const text = await res.text().catch(() => "");
    throw new Error(`wger request to ${path} failed: ${res.status} ${res.statusText}${text ? ` - ${text.slice(0, 200)}` : ""}`);
  }
  return (await res.json()) as T;
}

async function wgerGetAllPages<T>(path: string): Promise<T[]> {
  const results: T[] = [];
  let next: string | null = path;
  for (let page = 0; page < MAX_PAGES && next; page++) {
    // `next` is a full absolute URL from wger's own pagination after the
    // first page — wgerFetch always re-prefixes with baseUrl, so strip
    // that back off rather than teaching wgerFetch two different URL
    // shapes.
    const config = configOrNull();
    const relative: string = page === 0 || !config ? next : next.replace(config.baseUrl, "");
    const body: WgerPage<T> = await wgerGetJson<WgerPage<T>>(relative);
    results.push(...body.results);
    next = body.next;
  }
  return results;
}

export interface WgerConnectionStatus {
  connected: boolean;
  error: string | null;
}

/** "Test connection" — a lightweight, cheap authenticated read (see Phase 1's acceptance criteria in the implementation brief). Used by the admin tool/Settings surface to confirm wger_base_url/wger_api_token actually work, without needing to wait for the next scheduled poll. */
export async function testWgerConnection(): Promise<WgerConnectionStatus> {
  if (!isWgerConfigured()) return { connected: false, error: "not configured" };
  try {
    await wgerGetJson("/api/v2/workoutsession/?limit=1");
    return { connected: true, error: null };
  } catch (err) {
    return { connected: false, error: (err as Error).message };
  }
}

interface WgerLog {
  id: string;
  session: string | null;
  exercise: number;
  repetitions: string | number | null;
  weight: string | number | null;
  weight_unit: number | null;
}

interface WgerSession {
  notes: string | null;
}

interface WgerExerciseInfo {
  translations: { language: number; name: string }[];
}

// Exercise display names and the weight-unit id->name lookup are both
// effectively static for a given wger install (exercise metadata changes
// about as often as this app's own ACTIVITIES list does) — cached
// in-memory per server process rather than re-fetched on every call, same
// "in-memory cache, no persistence needed" spirit as
// broadcast.ts's computeFixedPeriodStats cache. A server restart just
// re-warms these on first use.
const exerciseNameCache = new Map<number, string>();
let weightUnitNameCache: Map<number, string> | null = null;

const ENGLISH_LANGUAGE_ID = 2;

async function getExerciseName(exerciseId: number): Promise<string> {
  const cached = exerciseNameCache.get(exerciseId);
  if (cached) return cached;
  try {
    const info = await wgerGetJson<WgerExerciseInfo>(`/api/v2/exerciseinfo/${exerciseId}/`);
    const translation = info.translations.find((t) => t.language === ENGLISH_LANGUAGE_ID) ?? info.translations[0];
    const name = translation?.name ?? `Exercise #${exerciseId}`;
    exerciseNameCache.set(exerciseId, name);
    return name;
  } catch {
    return `Exercise #${exerciseId}`;
  }
}

async function getWeightUnitName(unitId: number | null): Promise<string | null> {
  if (unitId == null) return null;
  if (!weightUnitNameCache) {
    const units = await wgerGetAllPages<{ id: number; name: string }>("/api/v2/setting-weightunit/");
    weightUnitNameCache = new Map(units.map((u) => [u.id, u.name]));
  }
  return weightUnitNameCache.get(unitId) ?? null;
}

function toNumberOrNull(value: string | number | null): number | null {
  if (value == null) return null;
  const n = typeof value === "number" ? value : parseFloat(value);
  return Number.isFinite(n) ? n : null;
}

/**
 * Today's (or any given date's) logged sets from the real wger instance,
 * reshaped into the same WorkoutSession/WorkoutSet shape the mock mirror
 * already used — one synthetic session per distinct wger session id
 * referenced by that day's logs (notes carried over from wger's own
 * workoutsession.notes), sets grouped under whichever session they
 * belong to. wger's own `date` filter on /api/v2/workoutlog/ does the
 * actual date scoping — confirmed against a live instance to filter
 * correctly by exact match (see this module's own header comment).
 *
 * Returns [] if wger isn't configured, the request fails, or there's
 * genuinely nothing logged that day — callers can't distinguish those from
 * the return value alone, same contract getWorkoutsForDate's mock
 * implementation already had (a transient wger outage just reads as "no
 * workout today" rather than surfacing an error to the Dashboard/viewer;
 * acceptable for a "pride" display, not for anything that needs to be
 * authoritative).
 */
export async function getWgerWorkoutsForDate(dateStr: string): Promise<WorkoutSession[]> {
  if (!isWgerConfigured()) return [];

  const logs = await wgerGetAllPages<WgerLog>(`/api/v2/workoutlog/?date=${dateStr}&limit=100`);
  if (logs.length === 0) return [];

  const exerciseIds = [...new Set(logs.map((l) => l.exercise))];
  const namesById = new Map<number, string>();
  await Promise.all(exerciseIds.map(async (id) => namesById.set(id, await getExerciseName(id))));

  const unitIds = [...new Set(logs.map((l) => l.weight_unit).filter((u): u is number => u != null))];
  const unitNamesById = new Map<number, string | null>();
  await Promise.all(unitIds.map(async (id) => unitNamesById.set(id, await getWeightUnitName(id))));

  const sessionIds = [...new Set(logs.map((l) => l.session).filter((s): s is string => !!s))];
  const notesBySessionId = new Map<string, string | null>();
  await Promise.all(
    sessionIds.map(async (id) => {
      try {
        const session = await wgerGetJson<WgerSession>(`/api/v2/workoutsession/${id}/`);
        notesBySessionId.set(id, session.notes || null);
      } catch {
        notesBySessionId.set(id, null);
      }
    }),
  );

  const NO_SESSION_KEY = "__no_session__";
  const logsBySessionKey = new Map<string, WgerLog[]>();
  for (const log of logs) {
    const key = log.session ?? NO_SESSION_KEY;
    const group = logsBySessionKey.get(key) ?? [];
    group.push(log);
    logsBySessionKey.set(key, group);
  }

  return [...logsBySessionKey.entries()].map(([key, sessionLogs]) => {
    const sets: WorkoutSet[] = sessionLogs.map((log, i) => ({
      id: log.id,
      exerciseName: namesById.get(log.exercise) ?? `Exercise #${log.exercise}`,
      weight: toNumberOrNull(log.weight),
      weightUnit: log.weight_unit != null ? unitNamesById.get(log.weight_unit) ?? null : null,
      reps: toNumberOrNull(log.repetitions) ?? 0,
      setOrder: i,
    }));
    return {
      id: key === NO_SESSION_KEY ? `wger-logs-${dateStr}` : key,
      date: dateStr,
      notes: key === NO_SESSION_KEY ? null : notesBySessionId.get(key) ?? null,
      sets,
    };
  });
}
